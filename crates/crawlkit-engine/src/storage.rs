    /// Parse a URL string with a fallback to "about:invalid".
    fn parse_url_safe(s: &str) -> Url {
        Url::parse(s).unwrap_or_else(|_| {
            Url::parse("about:invalid")
                .unwrap_or_else(|_| unreachable!("about:invalid is always valid"))
        })
    }

    /// Retrieve a single page by crawl ID and URL.
    ///
    /// Returns `None` if no page matches the given URL within the crawl.
    /// Checks the LRU cache first for recently accessed pages.
    pub fn get_page(&self, crawl_id: &str, url: &str) -> Result<Option<PageData>, StorageError> {
        {
            let mut cache = self.page_cache.lock();
            if let Some(page) = cache.get(&Self::cache_key(crawl_id, url)) {
                return Ok(Some(page.clone()));
            }
        }

        let conn = self.conn.lock();
        let result = conn.query_row(
            "SELECT id, url, final_url, status_code, title, description, canonical, word_count, load_time_ms, body_size, fetched_at, tenant_id, etag, last_modified, cwv_lcp, cwv_cls, cwv_inp, has_structured_data, schema_types, viewport_ok, has_csp, has_hsts, images_total, images_missing_alt, h1_count, heading_count, extractions
             FROM pages WHERE crawl_id = ?1 AND url = ?2",
            params![crawl_id, url],
            Self::row_to_page_data,
        );

        match result {
            Ok(page) => Ok(Some(page)),
            Err(rusqlite::Error::QueryReturnedNoRows) => Ok(None),
            Err(e) => Err(StorageError::Database(e)),
        }
    }

    /// Extract a `PageData` from a database row.
    fn row_to_page_data(row: &Row<'_>) -> Result<PageData, rusqlite::Error> {
        let url_str: String = row.get(1)?;
        let final_url_str: String = row.get(2)?;
        let canonical_str: Option<String> = row.get(6)?;
        let fetched_at_str: String = row.get(10)?;

        Ok(PageData {
            id: row.get(0)?,
            url: Self::parse_url_safe(&url_str),
            final_url: Self::parse_url_safe(&final_url_str),
            status_code: row.get(3)?,
            title: row.get(4)?,
            description: row.get(5)?,
            canonical_url: canonical_str.and_then(|s| Url::parse(&s).ok()),
            word_count: row.get::<_, Option<i64>>(7)?.map(|v| v as usize),
            load_time_ms: row.get::<_, Option<i64>>(8)?.map(|v| v as u64),
            body_size: row.get::<_, Option<i64>>(9)?.map(|v| v as usize),
            fetched_at: DateTime::parse_from_rfc3339(&fetched_at_str)
                .map(|dt| dt.with_timezone(&Utc))
                .unwrap_or_else(|_| Utc::now()),
            links: Vec::new(),
            tenant_id: row.get(11)?,
            etag: row.get(12)?,
            last_modified: row.get(13)?,
            cwv_lcp: row.get(14)?,
            cwv_cls: row.get(15)?,
            cwv_inp: row.get(16)?,
            has_structured_data: row.get::<_, Option<i64>>(17)?.map(|v| v != 0),
            schema_types: row.get(18)?,
            viewport_ok: row.get::<_, Option<i64>>(19)?.map(|v| v != 0),
            has_csp: row.get::<_, Option<i64>>(20)?.map(|v| v != 0),
            has_hsts: row.get::<_, Option<i64>>(21)?.map(|v| v != 0),
            images_total: row.get::<_, Option<i64>>(22)?.map(|v| v as usize),
            images_missing_alt: row.get::<_, Option<i64>>(23)?.map(|v| v as usize),
            h1_count: row.get::<_, Option<i64>>(24)?.map(|v| v as usize),
            heading_count: row.get::<_, Option<i64>>(25)?.map(|v| v as usize),
            extractions: row.get(26)?,
        })
    }

