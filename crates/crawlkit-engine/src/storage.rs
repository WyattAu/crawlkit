/// A page extracted from the crawl, with full data for storage.
///
/// Contains all metadata needed to persist a crawled page to the database,
/// including URL, status, content metrics, and discovered links.
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
pub struct PageData {
    /// Unique page identifier.
    pub id: String,
    /// The URL of the page.
    pub url: Url,
    /// The final URL after redirects.
    pub final_url: Url,
    /// The HTTP status code.
    pub status_code: u16,
    /// The page title.
    pub title: Option<String>,
    /// The meta description.
    pub description: Option<String>,
    /// The canonical URL.
    pub canonical_url: Option<Url>,
    /// Word count of the page body.
    pub word_count: Option<usize>,
    /// Response time in milliseconds.
    pub load_time_ms: Option<u64>,
    /// Body size in bytes.
    pub body_size: Option<usize>,
    /// When this page was fetched.
    pub fetched_at: DateTime<Utc>,
    /// Links discovered on this page.
    pub links: Vec<Url>,
    /// Tenant ID for multi-tenancy.
    pub tenant_id: Option<String>,
    /// ETag header value from the last fetch.
    pub etag: Option<String>,
    /// Last-Modified header value from the last fetch.
    pub last_modified: Option<String>,
    /// Largest Contentful Paint in milliseconds (lab measurement).
    pub cwv_lcp: Option<f64>,
    /// Cumulative Layout Shift (dimensionless, lab measurement).
    pub cwv_cls: Option<f64>,
    /// Interaction to Next Paint in milliseconds (lab measurement).
    pub cwv_inp: Option<f64>,
    /// Whether the page has any structured data (JSON-LD, microdata, RDFa).
    pub has_structured_data: Option<bool>,
    /// Comma-separated list of schema types present on the page.
    pub schema_types: Option<String>,
    /// Whether the viewport meta tag is properly configured.
    pub viewport_ok: Option<bool>,
    /// Whether the page has a Content-Security-Policy header.
    pub has_csp: Option<bool>,
    /// Whether the page has a Strict-Transport-Security header.
    pub has_hsts: Option<bool>,
    /// Total number of images on the page.
    pub images_total: Option<usize>,
    /// Number of images missing alt text.
    pub images_missing_alt: Option<usize>,
    /// Number of H1 headings on the page.
    pub h1_count: Option<usize>,
    /// Total number of headings (H1-H6) on the page.
    pub heading_count: Option<usize>,
    /// JSON-serialized custom extraction results: `Vec<(String, Vec<String>)>`.
    /// Each tuple is `(rule_name, extracted_values)`. `None` when no extraction
    /// rules are configured for the crawl.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub extractions: Option<String>,
}

